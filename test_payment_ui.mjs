import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
import 'fake-indexeddb/auto';

const dom=new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>',{url:'https://yero.test'});
for(const key of ['window','document','HTMLElement','HTMLInputElement','HTMLTextAreaElement','Event','MouseEvent','KeyboardEvent'])globalThis[key]=dom.window[key];
window.matchMedia=()=>({matches:true});
globalThis.IS_REACT_ACT_ENVIRONMENT=true;
const calls=[];globalThis.fetch=async(...args)=>{calls.push(args);throw new Error('Unexpected network request');};
await build({entryPoints:['src/MobileStudio.tsx'],outfile:'.test-cache/payment-ui-test.mjs',bundle:true,format:'esm',platform:'node',jsx:'automatic',loader:{'.css':'empty','.png':'file'},external:['react','react/jsx-runtime']});
const {createElement,act}=await import('react');
const {createRoot}=await import('react-dom/client');
const {MobileStudio}=await import('./.test-cache/payment-ui-test.mjs');
const root=createRoot(document.getElementById('root'));
const button=label=>[...document.querySelectorAll('button')].find(b=>(b.getAttribute('aria-label')||b.textContent.trim())===label);
const click=async(label)=>{const el=button(label);assert(el,`Missing button: ${label}`);await act(async()=>{el.dispatchEvent(new MouseEvent('click',{bubbles:true}));await Promise.resolve();});};
await act(()=>root.render(createElement(MobileStudio)));
await click('打开侧边栏');
await click('测试订单');
assert.match(document.body.textContent,/模拟购买次数/);
assert.match(document.body.textContent,/不.*真实|不.*付款/);
await click('进入模拟收银台');
await click('模拟支付成功');
assert.match(document.body.textContent,/模拟支付成功/);
assert.match(document.body.textContent,/不.*生图次数|未.*生图次数/);
assert.equal(calls.length,0,'Mock checkout never calls a real payment or generation API');
await click('重新测试');
await click('进入模拟收银台');
await click('模拟取消');
assert.match(document.body.textContent,/已取消模拟支付/);
await click('返回创作');
assert.equal(document.querySelector('[aria-label="模拟付款"]'),null);
await act(()=>root.unmount());
console.log('PASS: mock checkout success, cancel, return and no real payment calls');
