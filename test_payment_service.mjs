import assert from 'node:assert/strict';
import {build} from 'esbuild';

const result=await build({entryPoints:['src/paymentTest.ts'],bundle:true,write:false,format:'esm',platform:'neutral'});
const source=result.outputFiles[0].text;
const service=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const {TEST_PACKAGES,createOrder,finishOrder,getOrder}=service;
assert.equal(TEST_PACKAGES.length,2);
assert.deepEqual(TEST_PACKAGES.map(item=>item.id),['test-small','test-large']);
assert.throws(()=>createOrder({packageId:'unknown',method:'alipay'}));
assert.throws(()=>createOrder({packageId:'test-small',method:'other'}));
assert.throws(()=>createOrder(null));
assert.equal(getOrder('missing'),null);
assert.throws(()=>finishOrder('missing','success'));
const first=createOrder({packageId:'test-small',method:'alipay'});
assert.match(first.id,/^test-/);
assert.equal(first.status,'pending');
assert.equal(first.packageId,'test-small');
assert.equal(first.method,'alipay');
assert.throws(()=>finishOrder(first.id,'paid'));
assert.equal(getOrder(first.id).status,'pending');
const success=finishOrder(first.id,'success');
assert.equal(success.status,'success');
assert.deepEqual(finishOrder(first.id,'success'),success);
assert.deepEqual(finishOrder(first.id,'cancelled'),success,'A completed order cannot be changed');
const second=createOrder({packageId:'test-large',method:'wechat'});
assert.notEqual(second.id,first.id);
const cancelled=finishOrder(second.id,'cancelled');
assert.equal(cancelled.status,'cancelled');
assert.deepEqual(finishOrder(second.id,'success'),cancelled,'A cancelled order cannot be changed');
assert.equal(getOrder(first.id).status,'success');
assert.equal(getOrder(second.id).status,'cancelled');
assert.throws(()=>{success.status='pending';},TypeError,'Order snapshots cannot be mutated');
assert.doesNotMatch(source,/\b(fetch|XMLHttpRequest|localStorage|sessionStorage|indexedDB)\b/,'The mock has no network, persistence or production effects');
console.log('PASS: isolated simulated orders, validation, cancellation and idempotent completion');
